#!/usr/bin/env python3
"""把共享记忆源文件同步进各 AI 工具的注入点（零依赖，Python 3.8+）。

用法：
  1. 编辑下方 PAIRS：左边是共享源文件，右边是各工具"每会话自动注入"的目标文件
  2. python sync_memory.py
  3. 看输出的字符数，确认没超注入截断阈值

原理：在目标文件里维护一个 <!-- SYNC:BEGIN -->...<!-- SYNC:END --> 标记块，
每次把源文件全文替换进去。目标文件里标记块之外的内容不会被碰。
"""
import re
import pathlib

# ==== 按你的环境改这里 ====
SHARED = pathlib.Path(__file__).resolve().parent.parent / "_ai_shared"

PAIRS = [
    # (源文件, 目标注入文件)
    (SHARED / "project-rules.md", pathlib.Path.home() / ".codex" / "AGENTS.md"),
    # (SHARED / "L1-hot-memory.md", pathlib.Path.home() / ".workbuddy/<你的用户目录>/MEMORY.md"),
    # (SHARED / "project-rules.md", pathlib.Path.home() / ".agentB" / "rules.md"),
]
# =========================

HEAD = "<!-- SYNC:BEGIN generated by sync_memory.py, edit source not this block -->"
TAIL = "<!-- SYNC:END -->"


def build_block(src: pathlib.Path) -> str:
    return HEAD + "\n" + src.read_text(encoding="utf-8").strip() + "\n" + TAIL


def sync(src: pathlib.Path, dst: pathlib.Path) -> None:
    block = build_block(src)
    t = dst.read_text(encoding="utf-8") if dst.exists() else ""
    if HEAD in t and TAIL in t:
        t = re.sub(re.escape(HEAD) + r".*?" + re.escape(TAIL), lambda m: block, t, flags=re.S)
        act = "updated"
    else:
        t = (block + "\n\n" + t).strip()
        act = "written"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(t + "\n", encoding="utf-8")
    print(f"  {act}: {src.name} -> {dst}  ({len(t)} chars)")


if __name__ == "__main__":
    print("sync shared memory ->")
    for src, dst in PAIRS:
        if src.exists():
            sync(src, dst)
        else:
            print(f"  skip (source missing): {src}")
    print("done. re-run after editing source files.")
